import assert from 'node:assert/strict';
import worker, { LeoState } from '../cloudflare/worker.mjs';
const data = new Map();
const storage = { async get(k) { return data.get(k); }, async put(k,v) { data.set(k, structuredClone(v)); }, async transaction(fn) { return fn(this); } };
const object = new LeoState({ storage });
const env = { ALLOWED_ORIGIN: 'https://example.github.io', SYNC_KEY: 'a'.repeat(40), LEO_STATE: { idFromName: n=>n, get: ()=>object } };
const request = (method='GET',body,extra={}) => new Request('https://test.workers.dev/state', { method, headers: { Origin:env.ALLOWED_ORIGIN, Authorization:`Bearer ${env.SYNC_KEY}`, ...extra }, ...(body===undefined?{}:{body:JSON.stringify(body)}) });
assert.equal((await worker.fetch(request('GET',undefined,{Authorization:'bad'}),env)).status,401);
assert.equal((await worker.fetch(request('GET',undefined,{Origin:'https://other.test'}),env)).status,403);
assert.equal((await worker.fetch(request('OPTIONS'),env)).status,204);
assert.equal((await worker.fetch(request(),{})).status,503);
assert.deepEqual(await (await worker.fetch(request(),env)).json(),{revision:0,state:null});
const state={platforms:[{id:'ps',name:'PlayStation',limit:55}],days:{'2026-10-20':{limits:{ps:55},used:{ps:0}}},running:null};
let response=await worker.fetch(request('PUT',{revision:0,state}),env);
assert.equal(response.status,200);assert.equal((await response.json()).revision,1);
response=await worker.fetch(request('PUT',{revision:0,state:{...state,platforms:[]}}),env);
assert.equal(response.status,400);
response=await worker.fetch(request('PUT',{revision:0,state}),env);assert.equal(response.status,409);assert.equal((await response.json()).revision,1);
assert.deepEqual((await (await worker.fetch(request(),env)).json()).state,state);
assert.equal((await worker.fetch(request('PUT',{revision:1,state:{}}),env)).status,400);
console.log('OK: autenticación, origen, preflight, configuración, persistencia y rechazo de revisiones antiguas.');
